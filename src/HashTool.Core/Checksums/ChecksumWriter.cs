using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using HashTool.Core.Hashing;

namespace HashTool.Core.Checksums;

/// <summary>Output formats offered when exporting results.</summary>
public enum ExportFormat
{
    Gnu,
    Bsd,
    Sfv,
    Json,
    Csv
}

/// <summary>One file in an export.</summary>
/// <param name="Path">Path written to the file; use forward slashes for relative paths.</param>
public sealed record ChecksumLine(string Path, HashType Algorithm, string Hash, long? Size = null);

/// <summary>Writes checksum files that <c>sha256sum -c</c>, <c>shasum -c</c>, SFV tools and Hash Tool can read back.</summary>
public static class ChecksumWriter
{
    public static string Write(IEnumerable<ChecksumLine> lines, ExportFormat format, HexCase letterCase = HexCase.Lower)
    {
        using var writer = new StringWriter(CultureInfo.InvariantCulture) { NewLine = "\n" };
        Write(writer, lines, format, letterCase);
        return writer.ToString();
    }

    public static void Write(TextWriter writer, IEnumerable<ChecksumLine> lines, ExportFormat format, HexCase letterCase = HexCase.Lower)
    {
        ArgumentNullException.ThrowIfNull(writer);
        ArgumentNullException.ThrowIfNull(lines);
        var items = lines.ToList();

        switch (format)
        {
            case ExportFormat.Gnu:
                foreach (var line in items)
                {
                    var (escaped, name) = EscapeGnu(line.Path);
                    writer.WriteLine($"{(escaped ? "\\" : "")}{Case(line.Hash, letterCase)}  {name}");
                }

                break;
            case ExportFormat.Bsd:
                foreach (var line in items)
                    writer.WriteLine($"{HashAlgorithms.BsdTag(line.Algorithm)} ({line.Path}) = {Case(line.Hash, letterCase)}");
                break;
            case ExportFormat.Sfv:
                if (items.Any(l => l.Algorithm != HashType.CRC32))
                    throw new ArgumentException("SFV files can only contain CRC-32 checksums.", nameof(lines));
                writer.WriteLine("; Generated by Hash Tool");
                foreach (var line in items)
                    writer.WriteLine($"{line.Path} {Case(line.Hash, letterCase)}");
                break;
            case ExportFormat.Json:
                var report = items.Select(l => new ChecksumReportItem(l.Path, l.Size, HashAlgorithms.BsdTag(l.Algorithm),
                    Case(l.Hash, letterCase))).ToList();
                writer.WriteLine(JsonSerializer.Serialize(report, ChecksumJsonContext.Default.ListChecksumReportItem));
                break;
            case ExportFormat.Csv:
                writer.WriteLine("path,size,algorithm,hash");
                foreach (var line in items)
                {
                    writer.WriteLine(string.Join(',', Csv(line.Path),
                        line.Size?.ToString(CultureInfo.InvariantCulture) ?? "", HashAlgorithms.BsdTag(line.Algorithm),
                        Case(line.Hash, letterCase)));
                }

                break;
            default:
                throw new ArgumentOutOfRangeException(nameof(format), format, null);
        }
    }

    /// <summary>File extension conventionally used for an export, e.g. <c>sha256</c> or <c>sfv</c>.</summary>
    public static string SuggestedExtension(ExportFormat format, HashType? singleAlgorithm) => format switch
    {
        ExportFormat.Sfv => "sfv",
        ExportFormat.Json => "json",
        ExportFormat.Csv => "csv",
        _ when singleAlgorithm is { } a => HashAlgorithms.FileExtension(a),
        _ => "txt"
    };

    private static string Case(string hash, HexCase letterCase) =>
        letterCase == HexCase.Upper ? hash.ToUpperInvariant() : hash.ToLowerInvariant();

    private static (bool Escaped, string Name) EscapeGnu(string name)
    {
        if (name.IndexOfAny(['\\', '\n', '\r']) < 0) return (false, name);
        var builder = new StringBuilder(name.Length + 8);
        foreach (var c in name)
        {
            builder.Append(c switch
            {
                '\\' => "\\\\",
                '\n' => "\\n",
                '\r' => "\\r",
                _ => c.ToString()
            });
        }

        return (true, builder.ToString());
    }

    private static string Csv(string value)
    {
        // A leading = + - @ makes spreadsheet apps evaluate the cell as a formula (CSV injection).
        if (value.Length > 0 && value[0] is '=' or '+' or '-' or '@' or '\t' or '\r') value = "'" + value;
        return value.IndexOfAny([',', '"', '\n', '\r']) >= 0 ? $"\"{value.Replace("\"", "\"\"")}\"" : value;
    }
}

internal sealed record ChecksumReportItem(string Path, long? Size, string Algorithm, string Hash);

[JsonSourceGenerationOptions(WriteIndented = true, PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase,
    DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull)]
[JsonSerializable(typeof(List<ChecksumReportItem>))]
internal sealed partial class ChecksumJsonContext : JsonSerializerContext;
